// The logo as path data, for the cards, and the mark that moves while a page loads.
//
// `data/brand/mark.svg` is the one drawing of the mark: flat absolute paths, with no
// transform, clip or group, because neither card renderer applies a transform to a
// path. This writes it out as the path data the PDF and SVG renderers draw a
// `PathMark` from, scaled to a box one point tall, from which `logoMarks` in
// core/solve/index.js scales it to the band's type size.
//
// It also writes the loading mark from each drawing, light and dark: the two bubbles
// rock in turn, the back one anticlockwise and the front one clockwise, while the
// back one's three lines write themselves in, on a short loop. `.loading` in
// style.css shows it wherever a page is still loading or typesetting.
//
//   node scripts/build_logo.mjs        writes core/logo-shapes.js and data/brand/mark-loading*.svg

import { readFileSync, writeFileSync } from 'node:fs';

const svg = readFileSync(new URL('../data/brand/mark.svg', import.meta.url), 'utf8');
const view = /viewBox="([\d.-]+) ([\d.-]+) ([\d.-]+) ([\d.-]+)"/.exec(svg);
if (!view) throw new Error('data/brand/mark.svg has no viewBox');
const [vx, vy, vw, vh] = view.slice(1).map(Number);
/** @param {number} n */
const fmt = (n) => Number(n.toFixed(4)).toString();

// Absolute M/L/C/Z only, so every number is an x or a y in turn.
const shapes = [...svg.matchAll(/<path fill="(#[0-9a-f]{6})" d="([^"]+)"\/>/g)].map(([, fill, d]) => {
  if (/[^MLCZ\d\s.e-]/.test(d)) throw new Error(`mark.svg: a path is not absolute M/L/C/Z: ${d.slice(0, 40)}`);
  let k = 0;
  const unit = d.replace(/-?[\d.]+(?:e-?\d+)?/g, (n) => fmt((Number(n) - (k++ % 2 ? vy : vx)) / vh));
  return { d: unit, fill };
});
if (!shapes.length) throw new Error('data/brand/mark.svg has no paths');

const out = `// Generated by scripts/build_logo.mjs from data/brand/mark.svg -- do not edit.
//
// The mark as flat path data in a box one point tall and \`LOGO_ASPECT\` wide, in
// paint order. Coordinates alternate x, y throughout, which is what lets
// \`logoMarks\` scale and place it with one pass over the numbers.

export const LOGO_ASPECT = ${fmt(vw / vh)};

/** @type {{d:string, fill:string, stroke?:string, strokeWidth?:number}[]} */
export const LOGO_SHAPES = ${JSON.stringify(shapes, null, 2)};
`;
writeFileSync(new URL('../core/logo-shapes.js', import.meta.url), out);
console.log(`core/logo-shapes.js: ${shapes.length} shapes, aspect ${fmt(vw / vh)}`);

/**
 * A text line of the back bubble -- a capsule drawn M, L along the top, a cap, L along
 * the bottom, a cap -- as the stroke down its middle, so it can be drawn in.
 * @param {string} d
 */
function capsule(d) {
  const cmds = [...d.matchAll(/([MLC])([^MLCZ]+)/g)].map(([, c, nums]) => ({ c, p: nums.trim().split(/\s+/).map(Number) }));
  const ls = cmds.flatMap((cmd, i) => (cmd.c === 'L' ? [i] : []));
  if (cmds[0].c !== 'M' || ls.length !== 2) throw new Error(`mark.svg: a text line is not a capsule: ${d.slice(0, 40)}`);
  const [p0, p1, p3] = [cmds[0].p, cmds[ls[0]].p, cmds[ls[1]].p];
  const p2 = cmds[ls[1] - 1].p.slice(-2);
  const mid = (/** @type {number[]} */ a, /** @type {number[]} */ b) => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2];
  return { from: mid(p0, p3), to: mid(p1, p2), width: Math.hypot(p0[0] - p3[0], p0[1] - p3[1]) };
}

// One loop: the back bubble rocks while its lines write in, the front one answers,
// and the lines fade so the next loop writes them again.
const LOADING_STYLE = `
g { transform-box: fill-box; transform-origin: 50% 90%; animation: 3s ease-in-out infinite; }
.back { animation-name: back; }
.front { animation-name: front; }
line { stroke-dasharray: 1 2; animation: 3s linear infinite; }
.l1 { animation-name: l1; } .l2 { animation-name: l2; } .l3 { animation-name: l3; }
@keyframes back { 0%, 30%, 100% { transform: none; } 10% { transform: rotate(-8deg); } 18% { transform: rotate(3deg); } 24% { transform: rotate(-1deg); } }
@keyframes front { 0%, 50%, 80%, 100% { transform: none; } 60% { transform: rotate(8deg); } 68% { transform: rotate(-3deg); } 74% { transform: rotate(1deg); } }
@keyframes l1 { 0%, 5% { stroke-dashoffset: 1; } 20%, 85% { stroke-dashoffset: 0; opacity: 1; } 95%, 100% { stroke-dashoffset: 0; opacity: 0; } }
@keyframes l2 { 0%, 20% { stroke-dashoffset: 1; } 35%, 85% { stroke-dashoffset: 0; opacity: 1; } 95%, 100% { stroke-dashoffset: 0; opacity: 0; } }
@keyframes l3 { 0%, 35% { stroke-dashoffset: 1; } 50%, 85% { stroke-dashoffset: 0; opacity: 1; } 95%, 100% { stroke-dashoffset: 0; opacity: 0; } }
@media (prefers-reduced-motion: reduce) { g, line { animation: none; } line { stroke-dashoffset: 0; } }
`;

// Room for the tilt, which carries a bubble's far corner past the drawing's edge.
const pad = 0.12 * vh;
const loadingView = [vx - pad, vy - pad, vw + 2 * pad, vh + 2 * pad].map((v) => Number(v.toFixed(2))).join(' ');

for (const name of ['mark', 'mark-dark']) {
  const drawing = readFileSync(new URL(`../data/brand/${name}.svg`, import.meta.url), 'utf8');
  const paths = [...drawing.matchAll(/<path fill="(#[0-9a-f]{6})" d="([^"]+)"\/>/g)].map(([, fill, d]) => ({ fill, d }));
  // Paint order: the back bubble's outline, face and three lines, then the front bubble.
  if (paths.length !== 9) throw new Error(`${name}.svg: expected the mark's nine paths, found ${paths.length}`);
  const path = (/** @type {{fill:string, d:string}} */ p) => `<path fill="${p.fill}" d="${p.d}"/>`;
  const n = (/** @type {number} */ v) => Number(v.toFixed(2));
  const lines = paths.slice(2, 5).map((p, i) => {
    const { from, to, width } = capsule(p.d);
    return `<line class="l${i + 1}" x1="${n(from[0])}" y1="${n(from[1])}" x2="${n(to[0])}" y2="${n(to[1])}" stroke="${p.fill}" stroke-width="${n(width)}" stroke-linecap="round" pathLength="1"/>`;
  });
  const loading = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${loadingView}" aria-hidden="true">
<!-- Generated by scripts/build_logo.mjs from data/brand/${name}.svg; do not edit. -->
<style>${LOADING_STYLE}</style>
<g class="back">${path(paths[0])}${path(paths[1])}${lines.join('')}</g>
<g class="front">${paths.slice(5).map(path).join('')}</g>
</svg>
`;
  writeFileSync(new URL(`../data/brand/${name.replace('mark', 'mark-loading')}.svg`, import.meta.url), loading);
}
console.log('data/brand/mark-loading.svg, mark-loading-dark.svg');
