#!/usr/bin/env python3
"""Import exact face fills from an exported sheet or the three original sheets."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('source', type=Path, help='Exported SVG sheet, or directory containing the digits/uppercase/lowercase sheets')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
faces = json.loads(subprocess.check_output(['node', '-e', 'process.stdout.write(JSON.stringify(require(process.argv[1]).FACES))', str(root / 'core.js')], text=True))
sequences = {'digits': '0123456789', 'uppercase': 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'lowercase': 'abcdefghijklmnopqrstuvwxyz'}
colors = {'#8C1515': 'r', '#FFFFFF': 'w', 'none': '-'}
patterns = {}
sources = []
if args.source.is_file():
    patterns = json.loads(subprocess.check_output(['node', '-e', 'process.stdout.write(JSON.stringify(require(process.argv[1])))', str(root / 'edited-glyphs.js')], text=True))
    sources = json.loads((root / 'edited-glyphs.provenance.json').read_text())['sources']
    inputs = [(args.source, None)]
else:
    inputs = [(args.source / f'Cardinal-study-character-sheet-{group}.svg', expected) for group, expected in sequences.items()]
for path, expected in inputs:
    raw = path.read_bytes()
    document = ET.fromstring(raw)
    by_id = {element.get('id'): element for element in document.iter() if element.get('id')}
    for i, face in enumerate(faces):
        assert by_id[f'sheet-piece-{i}'].get('d') == face['d'], f'{path.name}: geometry mismatch at face {i}'
    labels = []
    blank = []
    cells = [element for element in document.iter() if element.get('id', '').startswith('sheet-cell-') and element.get('aria-label') is not None]
    if expected is not None:
        assert ''.join(cell.get('aria-label', '') for cell in cells) == expected, f'{path.name}: unexpected character order'
    assert cells, f'{path.name}: no character cells'
    for cell in cells:
        glyph = cell.get('aria-label', '')
        assert len(glyph) == 1 and 32 <= ord(glyph) <= 126 and glyph not in labels, f'{path.name}: invalid or duplicate character {glyph!r}'
        cell_id = cell.attrib['id']
        pattern = ''
        for j in range(len(faces)):
            element = by_id[f'{cell_id}-face-{j}']
            assert element.get('{http://www.w3.org/1999/xlink}href') == f'#sheet-piece-{j}'
            pattern += colors[element.attrib['fill']]
        patterns[glyph] = pattern
        labels.append(glyph)
        if 'r' not in pattern:
            blank.append(glyph)
    # Earlier source hashes still document the characters not replaced here.
    for source in sources:
        source['characters'] = ''.join(glyph for glyph in source['characters'] if glyph not in labels)
        source['blank'] = ''.join(glyph for glyph in source['blank'] if glyph not in labels)
    sources = [source for source in sources if source['characters']]
    sources.append({'file': path.name, 'sha256': hashlib.sha256(raw).hexdigest(), 'bytes': len(raw), 'characters': ''.join(labels), 'blank': ''.join(blank)})
content = '''/* Exact user-edited sheet fills. Generated by scripts/import-glyph-sheets.py. */
(function (global) {
  'use strict';
  // Positions follow PainterCore.FACES; r=cardinal, w=white, -=transparent.
  /** @type {Readonly<Record<string,string>>} */
  const patterns = Object.freeze(''' + json.dumps(patterns, ensure_ascii=False, indent=2) + ''');
  Object.assign(global, {PainterEditedGlyphs: patterns});
  if (typeof module !== 'undefined' && module.exports) module.exports = patterns;
})(typeof window !== 'undefined' ? window : globalThis);
'''
(root / 'edited-glyphs.js').write_text(content)
(root / 'edited-glyphs.provenance.json').write_text(json.dumps({'faceOrder': [face['id'] for face in faces], 'sources': sources}, indent=2) + '\n')
print(json.dumps({'imported': len(patterns), 'colored': sum('r' in p for p in patterns.values()), 'sources': sources}, indent=2))
