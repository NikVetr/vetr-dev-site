const { test, expect } = require("@playwright/test");

test("base-only selection and categorical GAM contrasts preserve their fitted specifications", async ({ page }) => {
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/ceo-salary-benchmark/");
  await page.locator("#chart-tab-model").click();
  await page.locator("#model-base-only").check();
  await expect(page.locator("#model-method")).toHaveValue("bayesian");
  await expect(page.locator("#model-training-count")).toHaveText("112");
  await page.locator("#model-base-only").uncheck();
  await expect(page.locator("#model-training-count")).toHaveText("124");
  await page.locator("#model-method").selectOption("gamCategorical");
  await expect(page.locator("#model-base-only")).toBeChecked();
  await expect(page.locator("#model-base-only")).toBeDisabled();
  await expect(page.locator("#model-category-inputs")).toBeVisible();
  await page.locator("#quantile-granularity").selectOption("custom");
  await page.locator("#custom-quantiles").fill("50");
  await page.locator("#custom-quantiles").blur();
  await page.locator("#model-focus").selectOption("__average__");
  const median = async () => Number(await page.locator(".quantile-cell").getAttribute("data-value"));
  const reference = await median();
  const focus = await page.evaluate(() => window.CEO_BENCHMARK_DATA.predictiveModel.models.gamCategorical.categoryEffects.focus_area);
  await page.locator("#model-focus").selectOption(focus.levels[0]);
  expect(Math.log(await median() / reference)).toBeCloseTo(focus.values[0], 7);
  await page.locator("#model-focus").selectOption("__mixture__");
  await page.locator('#model-focus-weights input[data-focus-index="0"]').fill("40");
  await page.locator('#model-focus-weights input[data-focus-index="7"]').fill("60");
  expect(Math.log(await median() / reference)).toBeCloseTo(.4 * focus.values[0] + .6 * focus.values[7], 7);
  await page.locator("#results-tab-model-details").click();
  await page.getByRole("button", { name: "Model specification: GAM · categorical · with other pay", exact: true }).click();
  const dialog = page.locator("#model-explanation-dialog");
  await expect(dialog).toContainText("Partially pooled categories");
  await expect(dialog).toContainText('s(field, bs = "re")');
  await expect(dialog).not.toContainText("Categorical profile settings, cash proxies, and job ads do not enter");
  await dialog.getByRole("button", { name: "Close model explanation" }).click();
  await page.waitForTimeout(150);
  await page.reload();
  await expect(page.locator("#model-method")).toHaveValue("gamCategorical");
  await expect(page.locator("#model-focus")).toHaveValue("__mixture__");
  expect(Math.log(await median() / reference)).toBeCloseTo(.4 * focus.values[0] + .6 * focus.values[7], 7);
  await page.screenshot({ path: "tmp/categorical-gam.png" });
  expect(errors).toEqual([]);
});
