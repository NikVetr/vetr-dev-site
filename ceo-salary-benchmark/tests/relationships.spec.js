const { test, expect } = require("@playwright/test");

test("record matrix supports features, transformations, layouts and scatter drill-down", async ({ page }) => {
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/ceo-salary-benchmark/");
  await page.locator("#chart-tab-scatter").click();
  await page.locator("#scatter-plot-mode").selectOption("matrix");
  const matrix = page.locator("#scatter-matrix");
  await expect(matrix.locator(".relationship-cell")).toHaveCount(16);
  await expect(matrix.locator(".relationship-feature-list")).toBeVisible();
  await expect(page.locator("#salary-chart")).toBeHidden();
  const cell = matrix.locator('.relationship-cell[data-x="expenses"][data-y="salary"]');
  expect(Number(await cell.getAttribute("data-n"))).toBeGreaterThan(20);
  const spearman = Number(await cell.getAttribute("data-correlation"));
  await matrix.getByLabel("Values", { exact: true }).selectOption("linear");
  expect(Number(await cell.getAttribute("data-correlation"))).toBeCloseTo(spearman, 10);
  await matrix.getByLabel("Correlation", { exact: true }).selectOption("pearson");
  const linearPearson = Number(await cell.getAttribute("data-correlation"));
  await matrix.getByLabel("Values", { exact: true }).selectOption("log");
  expect(Number(await cell.getAttribute("data-correlation"))).not.toBeCloseTo(linearPearson, 3);
  await matrix.getByLabel("Non-CEO highest-paid employee (40h)", { exact: true }).check();
  await expect(matrix.locator(".relationship-cell")).toHaveCount(25);
  await matrix.getByLabel("Layout", { exact: true }).selectOption("heatmap");
  await expect(matrix.locator("circle")).toHaveCount(0);
  await matrix.getByLabel("Layout", { exact: true }).selectOption("mixed-reverse");
  await expect(matrix.locator('.relationship-cell[data-x="expenses"][data-y="salary"] circle')).toHaveCount(0);
  await expect(matrix.locator('.relationship-cell[data-x="salary"][data-y="expenses"] circle').first()).toBeAttached();
  await page.screenshot({ path: "tmp/record-relationship-matrix.png" });
  await expect.poll(() => page.url()).toContain("?s=");
  const shared = page.url();
  await cell.focus(); await page.keyboard.press("Enter");
  await expect(page.locator("#scatter-plot-mode")).toHaveValue("bivariate");
  await expect(page.locator("#salary-chart .scatter-point").first()).toBeVisible();
  await expect(page.locator("#chart-title")).toContainText("Expenses");
  await page.goto(shared);
  await expect(page.locator("#scatter-plot-mode")).toHaveValue("matrix");
  await expect(matrix.locator(".relationship-cell")).toHaveCount(25);
  await matrix.getByRole("button", { name: "Expand ↗" }).click();
  const expanded = page.locator("#model-explanation-dialog");
  await expect(expanded.locator(".relationship-cell")).toHaveCount(25);
  for (const viewport of [{ width: 1440, height: 900 }, { width: 900, height: 650 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await expect(expanded.locator(".relationship-features")).toBeVisible();
    await expect.poll(() => expanded.evaluate((dialog) => {
      const matrix = dialog.querySelector(".relationship-matrix").getBoundingClientRect();
      const box = dialog.getBoundingClientRect();
      return matrix.width > 0 && matrix.height > 0 && matrix.right <= box.right && matrix.bottom <= box.bottom;
    })).toBe(true);
    await expect(expanded.locator(".relationship-controls select").first()).toHaveCSS("padding-right", "28px");
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: "tmp/record-relationship-expanded.png" });
  await expanded.getByLabel("Layout", { exact: true }).selectOption("heatmap");
  await expanded.getByRole("button", { name: "Close model explanation" }).click();
  await expect(matrix.locator("circle")).toHaveCount(0);
  while (await matrix.locator('input:checked').count()) await matrix.locator('input:checked').first().uncheck();
  await expect(matrix).toContainText("Select at least two features.");
  expect(errors).toEqual([]);
});

test("joint drivers preserve aligned draws, support model families and place close button at the corner", async ({ page }) => {
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/ceo-salary-benchmark/");
  await page.locator("#chart-tab-model").click();
  await page.locator("#results-tab-model-details").click();
  await page.locator("#model-joint-drivers").click();
  const dialog = page.locator("#model-explanation-dialog");
  await expect(dialog.locator(".relationship-cell")).toHaveCount(16);
  await expect(dialog.locator(".relationship-feature-list")).toBeVisible();
  const expected = await page.evaluate(() => {
    const artifact = window.CEO_BENCHMARK_DATA.predictiveModel;
    const row = artifact.comparison.find((row) => row.method === "bayesian" && row.includeHighestOtherPay && !row.includeAdvertisedRanges);
    const model = artifact.models[row.modelKey];
    const z = model.preprocessing.map((f) => (Math.log(artifact.rpProfile[f.key]) - f.center) / f.scale);
    const points = model.draws.beta.map((draw) => [draw[0] * z[0], draw[1] * z[1]]);
    const means = [0, 1].map((j) => points.reduce((s, p) => s + p[j], 0) / points.length);
    const cross = points.reduce((s, p) => s + (p[0] - means[0]) * (p[1] - means[1]), 0);
    const variances = [0, 1].map((j) => points.reduce((s, p) => s + (p[j] - means[j]) ** 2, 0));
    return { n: points.length, r: cross / Math.sqrt(variances[0] * variances[1]) };
  });
  const close = dialog.getByRole("button", { name: "Close model explanation" });
  const bounds = await dialog.boundingBox(), corner = await close.boundingBox();
  expect(corner.y - bounds.y).toBeLessThan(18);
  expect(bounds.x + bounds.width - corner.x - corner.width).toBeLessThan(18);
  await dialog.getByLabel("Values", { exact: true }).selectOption("log");
  const cell = dialog.locator('.relationship-cell[data-x="profile:0"][data-y="profile:1"]');
  const n = Number(await cell.getAttribute("data-n")); expect(n).toBeGreaterThan(250);
  expect(n).toBe(expected.n);
  expect(Number(await cell.getAttribute("data-correlation"))).toBeCloseTo(expected.r, 12);
  await dialog.getByLabel("Focus: AI / technology", { exact: true }).check();
  await expect(dialog.locator(".relationship-cell")).toHaveCount(25);
  await page.screenshot({ path: "tmp/joint-driver-matrix.png" });
  await cell.click();
  await expect(dialog.locator(".relationship-cell")).toHaveCount(1);
  await expect(dialog.getByRole("button", { name: "Back to matrix" })).toBeVisible();
  await dialog.getByRole("button", { name: "Back to matrix" }).click();
  const registry = await page.evaluate(() => window.CEO_BENCHMARK_DATA.predictiveModel.comparison);
  for (const family of ["linear", "gam", "svr", "gp", "bayesianGam", "bayesianExact"]) {
    const row = registry.find((row) => row.method === family && row.includeHighestOtherPay);
    await dialog.getByLabel("Joint uncertainty model").selectOption(row.key);
    await expect(dialog.locator(".relationship-cell")).toHaveCount(16);
    expect(Number(await dialog.locator('.relationship-cell[data-x="profile:0"][data-y="profile:1"]').getAttribute("data-correlation"))).toBeLessThanOrEqual(1);
    await expect(dialog.locator(".relationship-point").first()).toBeAttached();
  }
  await dialog.getByLabel("Joint uncertainty model").selectOption(registry.find((row) => row.method === "gp" && !row.includeHighestOtherPay).key);
  await expect(dialog.locator(".relationship-cell")).toHaveCount(9);
  await close.click();
  await expect(dialog).not.toBeVisible();
  expect(errors).toEqual([]);
});
