import assert from 'node:assert/strict';
import test from 'node:test';
import {openPage} from '../../scripts/landing-art/browser.mjs';
const engine=/** @type {'chromium'|'webkit'} */(process.env.BROWSER_ENGINE||'chromium');
test('funnel energy follows real parts, keyboard steps, Undo/Redo and coordinate changes',async()=>{
 const b=await openPage('intuitions/samplers/',{engine});const{page}=b;
 try{
  await page.waitForFunction(()=>!document.querySelector('#funnel-figures')?.hasAttribute('data-stale')&&document.querySelector('#funnel-energy svg'));
  await page.locator('#funnel-inspect-divergence').click();
  assert.match(await page.locator('#funnel-energy-readout').innerText(),/Divergence at step 13.*4234\.753 > 1000/);
  assert.equal(await page.locator('#funnel-transition').inputValue(),'32');
  assert.equal(await page.locator('#funnel-part').inputValue(),'39');
  assert.equal(await page.locator('#funnel-speed').inputValue(),'0.01');
  const threshold=await page.locator('.energy-threshold').evaluate((/** @type {SVGLineElement} */ el)=>({dash:getComputedStyle(el).strokeDasharray,threshold:Number(el.dataset.threshold),y:el.y1.baseVal.value,height:el.ownerSVGElement?.viewBox.baseVal.height}));
  assert.notEqual(threshold.dash,'none');assert.ok(threshold.y>0&&threshold.y<Number(threshold.height));
  assert.ok(threshold.threshold>1000&&threshold.threshold<1010);
  await page.locator('#funnel-trajectory-start').click();
  assert.equal(await page.locator('#funnel-part').inputValue(),'0');
  const values=()=>page.locator('#funnel-components dd').allTextContents();
  const start=await values();
  await page.locator('#funnel-part').focus();await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#funnel-integration').getAttribute('data-phase'),'momentum-first');
  assert.match(await page.locator('#funnel-part').getAttribute('aria-valuetext'),/First momentum half-step/);
  const half=await values();assert.equal(half[0],start[0]);assert.notEqual(half[1],start[1]);assert.equal(half[3],start[3]);
  assert.match(await page.locator('#funnel-energy-readout').innerText(),/not checked yet/);
  await page.keyboard.press('ArrowRight');
  const position=await values();assert.notEqual(position[0],half[0]);assert.equal(position[1],half[1]);
  assert.equal(await page.locator('#funnel-integration').getAttribute('data-phase'),'position');
  await page.locator('#funnel-next-part').focus();await page.keyboard.press('Enter');
  assert.equal(await page.locator('#funnel-integration').getAttribute('data-phase'),'momentum-last');
  assert.equal(await page.locator('#funnel-energy-plot').getAttribute('data-completed'),'1');
  await page.keyboard.press('Control+z');
  assert.equal(await page.locator('#funnel-part').inputValue(),'2');
  await page.keyboard.press('Control+Shift+z');
  assert.equal(await page.locator('#funnel-part').inputValue(),'3');
  assert.equal(await page.locator('#funnel-next-part').evaluate((/** @type {HTMLElement} */ el)=>el===document.activeElement),true);
  await page.locator('#funnel-play').click();await page.waitForTimeout(120);await page.locator('#funnel-transition').focus();
  assert.equal(await page.locator('#funnel-play').getAttribute('aria-pressed'),'false');
  await page.locator('#funnel-transition').fill('0');assert.equal(await page.locator('#funnel-transition').getAttribute('aria-invalid'),'true');
  await page.locator('#funnel-next-part').click();assert.equal(await page.locator('#funnel-transition').getAttribute('aria-invalid'),null);
  await page.locator('input[name="funnel-sampler"][value="rwm"]').check();
  await page.waitForFunction(()=>document.querySelector('#funnel-integration')?.hasAttribute('hidden'));
  await page.locator('input[name="funnel-sampler"][value="hmc"]').check();
  await page.locator('input[name="funnel-coordinates"][value="non-centred"]').check();
  await page.waitForFunction(()=>!document.querySelector('#funnel-figures')?.hasAttribute('data-stale')&&document.querySelector('#funnel-space svg'));
  assert.equal(await page.locator('#funnel-inspect-divergence').isDisabled(),true);
  assert.equal(await page.locator('#funnel-energy svg').count(),1);
  await page.setViewportSize({width:390,height:844});await page.emulateMedia({colorScheme:'dark'});
  await page.waitForTimeout(80);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(b.errors,[]);
 }finally{await b.close();}
});
