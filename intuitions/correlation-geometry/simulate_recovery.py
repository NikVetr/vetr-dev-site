"""Regenerate the recovery panel: OPENBLAS_NUM_THREADS=1 python3 simulate_recovery.py"""

from pathlib import Path
import json

import numpy as np


SEED = 1729
REPLICATES = 512
TARGET_N = 12
NEIGHBOR_NS = [12, 25, 50, 100, 200, 400]
EXPLAINED = np.arange(10) / 10


def nearest_correlations(observed, weights, tol=1e-8):
    """ADMM projection onto PSD, unit-diagonal matrices in weighted squared error."""
    invalid = np.linalg.eigvalsh(observed)[:, 0] < 0
    result = observed.copy()
    if not invalid.any():
        return result
    raw = observed[invalid]
    diag = np.arange(raw.shape[-1])
    w = weights / np.max(weights)
    fit = raw.copy()
    dual = np.zeros_like(fit)
    for _ in range(5000):
        prev = fit
        affine = (w * raw + fit - dual) / (w + 1)
        affine[:, diag, diag] = 1
        vals, vecs = np.linalg.eigh(affine + dual)
        fit = (vecs * np.maximum(vals, 0)[:, None, :]) @ vecs.swapaxes(-1, -2)
        dual += affine - fit
        if max(np.max(np.abs(affine - fit)), np.max(np.abs(fit - prev))) < tol:
            assert np.linalg.eigvalsh(affine).min() >= -1e-7
            result[invalid] = affine
            return result
    raise RuntimeError("Weighted projection failed to converge")


def normal_gram(rng, pairs, df):
    """Centered sums of squares and cross-products for independent standard normals."""
    length = np.sqrt(rng.chisquare(df, (REPLICATES, pairs)))
    along = rng.normal(size=length.shape)
    return np.array([length**2, length * along, along**2 + rng.chisquare(df - 1, length.shape)])


def sample_correlations(gram, rho):
    xx, xy, yy = gram
    residual_sd = np.sqrt(1 - rho**2)
    # Y = rho X + residual_sd Z. Reuse the same base noise across designs.
    cross = rho * xx + residual_sd * xy
    total_y = rho**2 * xx + 2 * rho * residual_sd * xy + residual_sd**2 * yy
    return cross / np.sqrt(xx * total_y)


def simulate():
    rng = np.random.default_rng(SEED)
    residual_r = rng.uniform(-0.8, 0.8, REPLICATES)
    target_gram = normal_gram(rng, 1, TARGET_N - 1)
    i, j = np.triu_indices(8, k=1)
    # Pair 0 is the target. The remaining 27 studies have separate respondents.
    # Centered Gaussian Gram matrices have n-1 independent normal contrasts.
    # Adding df = n_new - n_old keeps cohorts nested as the slider increases.
    neighbors = np.zeros((3, REPLICATES, len(i) - 1))
    previous_df = 0
    directions = np.array([1, 1, 1, -1, -1, -1])
    rows = []
    for n in NEIGHBOR_NS:
        neighbors += normal_gram(rng, len(i) - 1, n - 1 - previous_df)
        previous_df = n - 1
        weights = np.full((8, 8), n - 3)
        weights[0, 1] = weights[1, 0] = TARGET_N - 3
        for explained in EXPLAINED:
            target = 0.5 * explained + (1 - explained) * residual_r
            pop = np.eye(8)
            pop[0, 2:] = np.sqrt(explained / 6)
            pop[1, 2:] = np.sqrt(explained / 6) * (0.5 + np.sqrt(0.75) * directions)
            raw = np.tile(np.eye(8), (REPLICATES, 1, 1))
            raw[:, i[1:], j[1:]] = raw[:, j[1:], i[1:]] = sample_correlations(neighbors, pop[i[1:], j[1:]])
            raw[:, 0, 1] = raw[:, 1, 0] = sample_correlations(target_gram, target[:, None])[:, 0]
            equal = nearest_correlations(raw, np.ones((8, 8)))
            weighted = equal if n == TARGET_N else nearest_correlations(raw, weights)
            losses = np.array([(fit[:, 0, 1] - target)**2 for fit in (raw, equal, weighted)])
            rmse = np.sqrt(losses.mean(axis=1))
            paired = losses[0] / (2 * rmse[0]) - losses[2] / (2 * rmse[2])
            mc_se = paired.std(ddof=1) / np.sqrt(REPLICATES)
            rows.append(dict(neighborN=n, explained=float(explained), pairwise=round(float(rmse[0]), 7),
                             equal=round(float(rmse[1]), 7), weighted=round(float(rmse[2]), 7),
                             gainSE=round(float(mc_se), 7), indefinite=int((np.linalg.eigvalsh(raw)[:, 0] < 0).sum())))
    return rows


if __name__ == "__main__":
    invalid = np.full((1, 3, 3), -0.9)
    invalid[0, np.arange(3), np.arange(3)] = 1
    np.testing.assert_allclose(nearest_correlations(invalid, np.ones((3, 3)))[0, 0, 1], -0.5)
    rows = simulate()
    output = Path(__file__).with_name("recovery-grid.js")
    with output.open("w", encoding="utf-8") as f:
        f.write("// Generated by simulate_recovery.py. Each row scores the same target pairs.\n")
        for name, value in (("targetN", TARGET_N), ("replicates", REPLICATES), ("seed", SEED),
                            ("neighborNs", NEIGHBOR_NS), ("explainedLevels", EXPLAINED.tolist())):
            f.write(f"export const {name} = {json.dumps(value)};\n")
        f.write("export const designs = [\n")
        for row in rows:
            f.write("  " + json.dumps(row) + ",\n")
        f.write("];\n")
